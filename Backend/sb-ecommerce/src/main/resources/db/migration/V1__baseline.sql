
    create sequence products_seq start with 1 increment by 50;

    create table address (
        id bigint generated by default as identity,
        user_id bigint,
        building_name varchar(255) not null,
        city varchar(255) not null,
        country varchar(255) not null,
        pincode varchar(255) not null,
        state varchar(255) not null,
        street_name varchar(255) not null,
        primary key (id)
    );

    create table cart_items (
        discount float(53) not null,
        product_price float(53) not null,
        quantity integer,
        cart_id bigint,
        cart_item_id bigint generated by default as identity,
        product_id bigint,
        primary key (cart_item_id)
    );

    create table carts (
        total_price float(53),
        cart_id bigint generated by default as identity,
        user_id bigint unique,
        primary key (cart_id)
    );

    create table categories (
        categoryid bigint generated by default as identity,
        category_name varchar(255) not null,
        primary key (categoryid)
    );

    create table order_items (
        discount float(53) not null,
        ordered_product_price float(53) not null,
        quantity integer,
        order_id bigint,
        order_item_id bigint generated by default as identity,
        product_id bigint,
        primary key (order_item_id)
    );

    create table orders (
        order_date date,
        total_amount float(53),
        address_id bigint,
        order_id bigint generated by default as identity,
        payment_id bigint unique,
        email varchar(255) not null,
        order_status varchar(255),
        primary key (order_id)
    );

    create table payments (
        payments_id bigint generated by default as identity,
        payment_method varchar(255) not null,
        pg_name varchar(255),
        pg_payment_id varchar(255),
        pg_response_message varchar(255),
        pg_status varchar(255),
        primary key (payments_id)
    );

    create table products (
        discount float(53) not null,
        price float(53) not null,
        quantity integer not null check (quantity>=1),
        special_price float(53) not null,
        category_id bigint,
        product_id bigint not null,
        seller_id bigint,
        description varchar(255) not null,
        image varchar(255),
        product_name varchar(255) not null,
        primary key (product_id)
    );

    create table roles (
        role_id integer generated by default as identity,
        role_name varchar(20) check (role_name in ('ROLE_SELLER','ROLE_USER','ROLE_ADMIN')),
        primary key (role_id)
    );

    create table user_role (
        role_id integer not null,
        user_id bigint not null,
        primary key (role_id, user_id)
    );

    create table users (
        user_id bigint generated by default as identity,
        username varchar(20) not null,
        email varchar(50) not null,
        password varchar(120) not null,
        primary key (user_id),
        unique (username),
        unique (email)
    );

